/**
 * Generate the Library Catalog markdown from the *actual* default Library
 * registrations, so `docs/library-catalog/` can never drift from the code
 * (`pnpm generate:catalog`).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDefaultLibrary, DEFAULT_ASSETS } from '@mindforge/library';
import { DEFAULT_THEME_ID, getTheme } from '@mindforge/themes';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = join(root, 'docs', 'library-catalog');
const library = createDefaultLibrary();
const defaultTheme = getTheme(DEFAULT_THEME_ID);

const stamp = '<!-- Generated by `pnpm generate:catalog`. Do not edit by hand. -->';

function page(title: string, description: string, ids: string[]): string {
  const rows = ids.length
    ? ids.map((id) => `- \`${id}\``).join('\n')
    : '_None registered._';
  return `${stamp}\n\n# ${title}\n\n${description}\n\n${rows}\n`;
}

const assetRows = DEFAULT_ASSETS.map(
  (a) => `- \`${a.id}\` — ${a.kind}${a.procedural ? ' (procedural fallback)' : a.url ? ' (authored)' : ''}${a.description ? ` — ${a.description}` : ''}`,
).join('\n');

const assetPackRows = defaultTheme.assetPacks
  .map(
    (pack) =>
      `- \`${pack.id}\` — ${pack.maturity} — ${pack.label} (${pack.assetIds.length} assets)${pack.description ? ` — ${pack.description}` : ''}`,
  )
  .join('\n');

const files: Record<string, string> = {
  'characters.md': page(
    'Characters',
    'Registered character factories. Reference these ids from episode `entities[].factory`.',
    library.characters.list(),
  ),
  'prefabs.md': page(
    'Prefabs',
    'Registered theme-owned semantic scene assemblies. Reference from `prefab` entities via `factory`.',
    library.prefabs.list(),
  ),
  'motions.md': page(
    'Motions',
    'Registered humanoid and object motions. Reference from `motion`/`objectMotion` events.',
    library.motions.list(),
  ),
  'effects.md': page(
    'Effects',
    'Registered effects (contours, signals, bursts, reveals). Reference from `effect` events.',
    library.effects.list(),
  ),
  'cameras.md': page(
    'Cameras',
    'Registered camera shot presets. Reference from `camera` events via `preset`.',
    library.cameras.list(),
  ),
  'environments.md': page(
    'Environments',
    'Registered domains / stages. Reference from an episode `environment`.',
    library.environments.list(),
  ),
  'scene-layers.md': page(
    'Scene Layers',
    'Registered reusable world-composition systems. Reference from `layers[].factory`.',
    library.sceneLayers.list(),
  ),
  'audio.md': page(
    'Audio',
    'Registered semantic audio cues. Reference from `audio` timeline events via `cue`.',
    library.audio.list(),
  ),
  'assets.md': `${stamp}\n\n# Assets\n\nRegistered asset descriptors. Procedural entries are deterministic fallbacks; URL-backed entries must satisfy the PF2 authored-model contract.\n\n${assetRows}\n`,
  'asset-packs.md': `${stamp}\n\n# Asset Packs\n\nDefault-theme production/fallback asset groupings. A pack becomes \`production\` only when every listed asset is production-ready.\n\n${assetPackRows || '_None registered._'}\n`,
};

for (const [name, content] of Object.entries(files)) {
  writeFileSync(join(outDir, name), content, 'utf8');
  console.log(`  wrote docs/library-catalog/${name}`);
}
console.log('\nLibrary catalog generated.');
